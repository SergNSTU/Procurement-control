using System.Collections.ObjectModel;
using CommunityToolkit.Mvvm.ComponentModel;

namespace ProcurementControl.ViewModels;

/// <summary>Один раздел инструкций: название в списке + текст.</summary>
public sealed record InstructionSection(string Title, string Body);

/// <summary>
/// Страница «Инструкции» — перенос $instructionsPage (RRFQComparer.ps1,
/// строки 3296-3412). Список разделов слева, текст справа. Содержимое
/// соответствует оригинальному $instructionSections.
/// </summary>
public partial class InstructionsViewModel : ObservableObject
{
    [ObservableProperty]
    private InstructionSection? _selectedSection;

    public ObservableCollection<InstructionSection> Sections { get; } = new();

    public InstructionsViewModel()
    {
        Sections.Add(new InstructionSection("FAQ", """
            FAQ по приложению

            Что делает приложение?
            Приложение сравнивает RRFQ поставщиков, ведет контроль закупки, хранит документы, историю действий, задачи и базу квот.

            Где лучше работать?
            Сейчас используется только основная стабильная desktop-версия.

            Как тестировать без мусора?
            В "База квот" можно удалить выбранные строки или очистить базу. В "История" можно очистить журнал действий.
            """));

        Sections.Add(new InstructionSection("Сравнение RRFQ", """
            Сравнение RRFQ

            1. Выберите исходный RFQ.
            2. Добавьте файлы поставщиков.
            3. Выберите приоритет: цена или срок.
            4. Нажмите "Сформировать preview".
            5. Проверьте победителей, предупреждения и несопоставленные строки.
            6. При необходимости выберите квоту вручную или заполните предложение вручную.
            7. Нажмите "Создать результирующий RRFQ".

            База квот заполняется после анализа RRFQ: сохраняются все найденные квоты, а не только победители.
            """));

        Sections.Add(new InstructionSection("Контроль закупки", """
            Контроль закупки

            1. Создайте сделку вручную или импортируйте результирующий RRFQ.
            2. Заполните клиента, период, статус и комментарий.
            3. Добавьте поставщиков.
            4. Загрузите PI/ERP/прочие документы.
            5. Отмечайте оплату, ERP, подтверждение инвойса и поступление.

            Документы копируются в локальное хранилище приложения. При удалении сделки удаляется и папка сделки.
            """));

        Sections.Add(new InstructionSection("Задачи", """
            Задачи

            Раздел нужен для оперативного отслеживания задач.

            При создании строки автоматически создается папка в data\components\files.
            Если заполнить номер сделки, папка переименуется с учетом этого номера.
            При удалении строки задачи ее папка также удаляется.
            """));

        Sections.Add(new InstructionSection("Перенос", """
            Перенос на другой компьютер

            Скопируйте всю папку проекта целиком: app, config, data, Start.bat и Start.vbs.

            На другом компьютере нужен Microsoft Excel.
            Для считывания сумм из PDF желательно наличие Microsoft Word.

            Если в настройках документов указан внешний путь, перенесите и эту папку либо верните путь внутрь папки приложения.
            """));

        Sections.Add(new InstructionSection("Outlook", """
            Интеграция с Outlook

            Приложение работает с установленным на компьютере Outlook.

            Напоминания:
            Кнопка "В Outlook" (или пункт контекстного меню) создаёт в календаре Outlook
            встречу-напоминание на 9:00 даты выбранного пункта.

            Задачи:
            Кнопка "Задача в Outlook" создаёт задачу Outlook: тема = сделка + описание,
            срок берётся из колонки "Напоминание" (если пусто — из дедлайна),
            приоритет переносится ("Срочно"/1/2 — высокая важность).

            Письма:
            Кнопка "Письмо" по выбранной задаче открывает черновик письма в Outlook
            с темой по сделке и краткой сводкой; адрес получателя вводится в диалоге.
            Письмо не отправляется автоматически — вы проверяете и отправляете его сами.

            Автоимпорт RRFQ из почты (тест):
            Галочка "Импорт RRFQ из почты" на странице "Контроль закупки" включает
            слежение за ящиком comp@npkexpert.ru (раз в минуту). Если от внешнего
            отправителя приходит письмо с номером АКТИВНОЙ сделки (фильтр "Активные")
            в теме и Excel-вложением (.xlsx/.xlsm/.xls), файл автоматически
            загружается в документы этой сделки как RRFQ.

            Поставщики: если адрес отправителя есть в таблице соответствий
            (sales5@chipera.net → CPR, huananshengke@163.com → HNN, vivi@bomzon.com → BMZ,
            kotakoti@optechic.com → OPT, sales12@/sales17@allpartsic.cn → CRL,
            xinkeweiltd@126.com → TIM, purp-d@/purp-e@/purp-b@moscentech.com и
            benjamin401@163.com → Ben), поставщик с этим именем автоматически
            создаётся у сделки, а RRFQ привязывается к нему и кладётся в его папку.
            Неизвестные адреса: документ попадает в сделку без привязки,
            папка = адрес отправителя.

            Имена файлов сохраняются как пришли от поставщика; файлы с именем
            "RFQ_..." или "RFQ ..." (с пробелом) переименовываются в "RRFQ_...".

            При загрузке файлов появляется уведомление "Пришли RRFQ файлы" со
            списком: сделка, файл, поставщик. Оно висит поверх всех окон, пока
            вы не нажмёте ОК (или крестик) — само не исчезает.

            Ручная проверка — меню "⋯" → "Проверить почту поставщиков".
            Обработанные письма запоминаются, файлы не дублируются. Приложение
            только читает почту: ничего не отправляет и не удаляет.

            Если Outlook не установлен или не запускается, приложение покажет сообщение об ошибке.
            """));

        SelectedSection = Sections[0];
    }
}
